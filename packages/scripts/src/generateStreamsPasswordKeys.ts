import { readFileSync, writeFileSync } from "node:fs";
import type { OpenAPIV3_1 } from "openapi-types";

/**
 * Collects the property names marked `format: "password"` on the Stream
 * Processing schemas (`Streams*`) of the Atlas Admin API spec.
 * `redactSensitiveKeys` unions this set with its curated list so tool output
 * never leaks values of fields the API classifies as passwords (e.g.
 * `sslKey`).
 *
 * Scoped to `Streams*` schemas because that is the only surface whose
 * responses can carry these values; other schemas' password fields (log
 * integrations, OTel headers) never appear in streams tool output.
 *
 * Runs as part of `packages/scripts/generate.sh`, right after
 * `openapi-typescript` emits `openapi.d.ts`, so the generated key set and the
 * generated types always come from the same spec snapshot.
 */

const streamsPasswordProperties = (schema: OpenAPIV3_1.SchemaObject, into: Set<string>): void => {
    for (const [name, property] of Object.entries(schema.properties ?? {})) {
        if (
            property !== null &&
            typeof property === "object" &&
            !("$ref" in property) &&
            property.format === "password"
        ) {
            into.add(name);
        }
    }
};

function main(): void {
    const [specPath, outPath] = process.argv.slice(2);
    if (!specPath || !outPath) {
        console.error("Usage: tsx generatePasswordKeys.ts <bundledSpec.json> <output .ts file>");
        process.exit(1);
    }
    const spec = JSON.parse(readFileSync(specPath, "utf8")) as OpenAPIV3_1.Document;
    const passwordKeys = new Set<string>();
    for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
        if (name.startsWith("Streams")) {
            streamsPasswordProperties(schema, passwordKeys);
        }
    }

    const sorted = [...passwordKeys].sort();
    const output = `/**
 * This file was auto-generated by packages/scripts/src/generateStreamsPasswordKeys.ts
 * from the Atlas Admin API OpenAPI spec, as part of packages/scripts/generate.sh.
 * Do not edit it directly; regenerate with:
 *   pnpm --filter @mongodb-js/mcp-scripts generate:openapi-password-keys <bundledSpec.json> <output .ts file>
 */

export const STREAMS_PASSWORD_PROPERTIES: readonly string[] = ${JSON.stringify(sorted, null, 4)};
`;

    writeFileSync(outPath, output, "utf8");
    console.log(`Generated ${outPath} with ${sorted.length} Streams password properties.`);
}

main();
